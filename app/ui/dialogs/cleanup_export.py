"""
Cleanup Export — save a Cleanup Recommendations report to CSV or Markdown.
"""

from __future__ import annotations

import csv
import io
from pathlib import Path
from tkinter import filedialog, messagebox
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from app.core.cleanup import CleanupRecommendation


def export_cleanup_report(
    recs: "list[CleanupRecommendation]",
    *,
    scan_paths: list[str] | None = None,
    parent=None,
) -> bool:
    """
    Open a save-file dialog and write the cleanup report.

    Returns True when a file was written, False when the user cancelled.
    """
    from app.core.cleanup import generate_cleanup_report_rows  # noqa: PLC0415

    rows = generate_cleanup_report_rows(recs, scan_paths=scan_paths)
    if not rows:
        messagebox.showinfo(
            "Nothing to export",
            "No redundant-format rows found. Run a scan and select a DAW profile first.",
            parent=parent,
        )
        return False

    path_str = filedialog.asksaveasfilename(
        parent=parent,
        title="Export Cleanup Report",
        defaultextension=".csv",
        filetypes=[
            ("CSV", "*.csv"),
            ("Markdown", "*.md"),
            ("All files", "*.*"),
        ],
        initialfile="studio-vault-cleanup-report",
    )
    if not path_str:
        return False

    out = Path(path_str)
    try:
        if out.suffix.lower() == ".md":
            out.write_text(_to_markdown(rows), encoding="utf-8")
        else:
            out.write_text(_to_csv(rows), encoding="utf-8")
    except OSError as exc:
        messagebox.showerror("Export failed", str(exc), parent=parent)
        return False

    messagebox.showinfo(
        "Export complete",
        f"Saved {len(rows)} rows to:\n{out}",
        parent=parent,
    )
    return True


# ── Formatters ────────────────────────────────────────────────────────────────

_COLUMNS = [
    "Product",
    "Developer",
    "Installed Formats",
    "Keep Formats",
    "Redundant Format",
    "File Path",
    "Actionability",
    "Reason",
    "Est. Recoverable",
    "Est. Recoverable (bytes)",
    "Confidence",
    "Suggested Action",
]


def _to_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=_COLUMNS, extrasaction="ignore", lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return buf.getvalue()


def _to_markdown(rows: list[dict]) -> str:
    lines: list[str] = [
        "# Studio Vault — Cleanup Report",
        "",
        "Generated by Studio Vault.  "
        "System-locked items require the vendor's installer or Reveal in Finder.",
        "",
    ]

    # Summary block
    actionable = sum(1 for r in rows if r["Actionability"] in ("Can Quarantine", "Choose Format"))
    locked      = sum(1 for r in rows if r["Actionability"] == "System Locked")
    already_q   = sum(1 for r in rows if r["Actionability"] == "Already Quarantined")
    try:
        total_bytes = sum(int(r.get("Est. Recoverable (bytes)", 0) or 0) for r in rows)
        from app.core.scanner import _fmt_size  # noqa: PLC0415
        total_human = _fmt_size(total_bytes) if total_bytes else "—"
    except Exception:
        total_human = "—"

    lines += [
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Total redundant copies | {len(rows)} |",
        f"| Actionable (quarantinable) | {actionable} |",
        f"| System-locked (manual cleanup) | {locked} |",
        f"| Already quarantined | {already_q} |",
        f"| Est. total recoverable | {total_human} |",
        "",
    ]

    # Detail table
    headers = ["Product", "Developer", "Redundant Format", "File Path",
               "Actionability", "Est. Recoverable", "Confidence", "Suggested Action"]
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("| " + " | ".join("---" for _ in headers) + " |")

    for row in rows:
        cells = [
            _md_escape(row.get("Product", "")),
            _md_escape(row.get("Developer", "")),
            row.get("Redundant Format", ""),
            f"`{_md_escape(row.get('File Path', ''))}`",
            row.get("Actionability", ""),
            row.get("Est. Recoverable", ""),
            row.get("Confidence", ""),
            _md_escape(row.get("Suggested Action", "")),
        ]
        lines.append("| " + " | ".join(cells) + " |")

    lines.append("")
    return "\n".join(lines)


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")
